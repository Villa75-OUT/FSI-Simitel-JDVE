    private void TDetallesMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TDetallesMousePressed
           int f = TDetalles.getSelectedRow();
        if (f >= 0) {
            TDetRecetaNum.setText(TDetalles.getValueAt(f, 0).toString());
            TDetMedClave.setText(TDetalles.getValueAt(f, 1).toString());
            TDosis.setText(TDetalles.getValueAt(f, 2).toString());
            TFrecuencia.setText(TDetalles.getValueAt(f, 3).toString());
            TDetDuracion.setText(TDetalles.getValueAt(f, 4).toString());
            TObservacion.setText(TDetalles.getValueAt(f, 5).toString());
            
            
            TDetRecetaNum.setEditable(false); 
        TDetMedClave.setEditable(false);  
        }
    }//GEN-LAST:event_TDetallesMousePressed

    private void BinsertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BinsertarActionPerformed
        
        
    try {
        if (jTabbedPane1.getSelectedIndex() == 0) {
            Object[] res = cnx.ejecutarCRUD(
                "gestionar_receta",
                new Object[]{
                    "INSERT",
                    Integer.parseInt(TNumero.getText().trim()),
                    TFecha.getText().trim(),
                    TDuracion.getText().trim(),
                    TVigencia.getText().trim(),
                    CBEstado.getSelectedItem().toString().trim(),
                    Integer.parseInt(TFConsultaFolio.getText().trim())
                }
            );
            JOptionPane.showMessageDialog(this, "Estado: " + res[0] + "\nMensaje: " + res[1]);
            if (Integer.parseInt(res[0].toString()) == 1) {
                cnx.entablar(sqlRecetas, TRecetas);
            }
        } else {
            Object[] res = cnx.ejecutarCRUD(
                "gestionar_detalle_receta",
                new Object[]{
                    "INSERT",
                    Integer.parseInt(TDetRecetaNum.getText().trim()),
                    Integer.parseInt(TDetMedClave.getText().trim()),
                    TDosis.getText().trim(),
                    TFrecuencia.getText().trim(),
                    TDetDuracion.getText().trim(),
                    TObservacion.getText().trim()
                }
            );
            JOptionPane.showMessageDialog(this, "Estado: " + res[0] + "\nMensaje: " + res[1]);
            if (Integer.parseInt(res[0].toString()) == 1) {
                cnx.entablar(sqlDetalles, TDetalles);
            }
        }
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Verifica que los campos numéricos tengan números válidos");
    }

        
    }//GEN-LAST:event_BinsertarActionPerformed

