    private void TRecetasMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TRecetasMousePressed
        int f = TRecetas.getSelectedRow();
        if (f >= 0) {
            TNumero.setText(TRecetas.getValueAt(f, 0).toString());
            TFecha.setText(TRecetas.getValueAt(f, 1).toString());
            TDuracion.setText(TRecetas.getValueAt(f, 2).toString());
            TVigencia.setText(TRecetas.getValueAt(f, 3).toString());
            CBEstado.setSelectedItem(TRecetas.getValueAt(f, 4).toString());
            TFConsultaFolio.setText(TRecetas.getValueAt(f, 5).toString());
            
            TNumero.setEditable(false);
            
        }
        
    }//GEN-LAST:event_TRecetasMousePressed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    if (jTabbedPane1.getSelectedIndex() == 0) {
        TNumero.setText("");
        TFecha.setText("");
        TDuracion.setText("");
        TVigencia.setText("");
        CBEstado.setSelectedIndex(0);
        TFConsultaFolio.setText("");

        TNumero.setEditable(true);
        TRecetas.clearSelection();
    } else {
        TDetRecetaNum.setText("");
        TDetMedClave.setText("");
        TDosis.setText("");
        TFrecuencia.setText("");
        TDetDuracion.setText("");
        TObservacion.setText("");

        TDetRecetaNum.setEditable(true);
        TDetMedClave.setEditable(true);
        TDetalles.clearSelection();
    }

    }//GEN-LAST:event_jButton1ActionPerformed

    
   
    
